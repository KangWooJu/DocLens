"""합성 Antora 사이트와 합성 git 트리를 메모리에서 생성, 실제 문서 원본은 쓰지 않음"""

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{title} :: Synthetic Docs</title>
<meta name="version" content="{version}">
<meta name="versioned-url" content="https://docs.spring.io{root}{name}">
</head>
<body class="article">
<div class="nav-container"><div class="nav-panel-menu is-active">
<nav class="nav-menu">
<ul class="nav-list">
{nav}
</ul>
</nav>
</div></div>
<main class="article">
<div class="content">
<article class="doc">
<h1 id="page-title" class="page">{title}</h1>
<div class="sect1">
<h2 id="overview"><a class="anchor" href="#overview"></a>Overview</h2>
<div class="sectionbody">
<div class="paragraph"><p>This synthetic page {title} describes a made-up feature so the collector has
enough article text to read. It is generated by the test fixture and is not a real document.</p></div>
</div>
</div>
</article>
<div class="edit-this-page">
<a href="https://github.com/spring-projects/{project}/blob/v{version}/docs/{name}.adoc">Edit this Page</a>
</div>
</div>
</main>
<footer class="footer"><p>Synthetic footer text for tests only.</p></footer>
</body>
</html>
"""
ROBOTS = "User-agent: *\nAllow: /\n"


def page_names(pages: int) -> list[str]:
    return ["index.html", *(f"p{index:03d}.html" for index in range(pages - 1))]


def site(
    project: str = "spring-boot",
    version: str = "4.1.3",
    pages: int = 150,
    robots: str = ROBOTS,
) -> dict[str, bytes]:
    """path별 응답 본문, 모든 쪽에 같은 nav, robots.txt 포함"""

    root = f"/{project}/{version.rsplit('.', 1)[0]}/reference/"
    names = page_names(pages)
    nav = "\n".join(f'<li class="nav-item"><a class="nav-link" href="{name}">{name}</a></li>' for name in names)
    pages_by_path = {
        root + name: PAGE.format(
            title=name.removesuffix(".html"),
            version=version,
            root=root,
            name=name,
            nav=nav,
            project=project,
        ).encode("utf-8")
        for name in names
    }
    return {"/robots.txt": robots.encode("utf-8"), **pages_by_path}


GIT_PAGE = """= Synthetic {title}

[[overview]]
== Overview

This synthetic page {title} is written by the test fixture and is not a real document.

include-code::MyApplication[]
"""
# 합성 git 트리의 저장소 경로, 쪽과 include
GIT_PAGES = (
    "docs/antora/pages/index.adoc",
    "docs/antora/pages/web/servlet.adoc",
    "docs/antora/pages/data/sql.adoc",
)
GIT_INCLUDES = (
    "docs/src/main/java/example/MyApplication.java",
    "docs/src/main/kotlin/example/MyApplication.kt",
    "docs/antora/partials/dockerfile",
)
# 목록에 없는 파일, 송신되면 안 됨
GIT_UNLISTED = "docs/antora/pages/unlisted.adoc"


def git_base(commit: str) -> str:
    return f"/spring-projects/spring-boot/{commit}/"


def git_tree(
    commit: str,
    version: str = "4.1.2",
) -> dict[str, bytes]:
    """path별 raw 본문, robots.txt 없음(raw host처럼 404)"""

    files = {
        "gradle.properties": f"# synthetic build properties\nversion={version}\nlatestVersion=false\n",
        **{
            path: GIT_PAGE.format(title=path.rsplit("/", 1)[-1].removesuffix(".adoc"))
            for path in (*GIT_PAGES, GIT_UNLISTED)
        },
        GIT_INCLUDES[0]: "package example;\n\n// tag::main[]\npublic class MyApplication {\n}\n// end::main[]\n",
        GIT_INCLUDES[1]: "package example\n\n// tag::main[]\nclass MyApplication\n// end::main[]\n",
        GIT_INCLUDES[2]: "FROM synthetic-base\nCOPY app.jar /app.jar\n",
    }
    return {git_base(commit) + path: body.encode("utf-8") for path, body in files.items()}
